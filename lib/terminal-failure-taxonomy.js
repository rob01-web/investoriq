export const TERMINAL_FAILURE_CODES = Object.freeze({
  CORE_T12_CATASTROPHICALLY_UNUSABLE: "CORE_T12_CATASTROPHICALLY_UNUSABLE",
  CORE_RENT_ROLL_CATASTROPHICALLY_UNUSABLE: "CORE_RENT_ROLL_CATASTROPHICALLY_UNUSABLE",
  CORE_PACKAGE_FUNDAMENTALLY_CONTRADICTORY: "CORE_PACKAGE_FUNDAMENTALLY_CONTRADICTORY",
  SOURCE_TRUTH_PACKAGE_CONSTRUCTION_FAILED: "SOURCE_TRUTH_PACKAGE_CONSTRUCTION_FAILED",
  REPORT_RENDER_FAILED: "REPORT_RENDER_FAILED",
  REPORT_CONTRACT_FAILED: "REPORT_CONTRACT_FAILED",
  PDF_ARTIFACT_FAILED: "PDF_ARTIFACT_FAILED",
  STORAGE_PUBLICATION_FAILED: "STORAGE_PUBLICATION_FAILED",
});

const DOCUMENT_REPLACEMENT_CODES = new Set([
  TERMINAL_FAILURE_CODES.CORE_T12_CATASTROPHICALLY_UNUSABLE,
  TERMINAL_FAILURE_CODES.CORE_RENT_ROLL_CATASTROPHICALLY_UNUSABLE,
  TERMINAL_FAILURE_CODES.CORE_PACKAGE_FUNDAMENTALLY_CONTRADICTORY,
]);

const INTERNAL_SYSTEM_FAILURE_CODES = new Set([
  TERMINAL_FAILURE_CODES.SOURCE_TRUTH_PACKAGE_CONSTRUCTION_FAILED,
  TERMINAL_FAILURE_CODES.REPORT_RENDER_FAILED,
  TERMINAL_FAILURE_CODES.REPORT_CONTRACT_FAILED,
  TERMINAL_FAILURE_CODES.PDF_ARTIFACT_FAILED,
  TERMINAL_FAILURE_CODES.STORAGE_PUBLICATION_FAILED,
]);

export function classifyTerminalFailureCode(code = "") {
  const normalized = String(code || "").trim().toUpperCase();
  if (DOCUMENT_REPLACEMENT_CODES.has(normalized)) {
    return {
      code: normalized,
      failure_class: "customer_document_failure",
      customer_document_replacement_required: true,
      retry_safe: false,
    };
  }
  if (INTERNAL_SYSTEM_FAILURE_CODES.has(normalized)) {
    return {
      code: normalized,
      failure_class: "internal_system_failure",
      customer_document_replacement_required: false,
      retry_safe: true,
    };
  }
  return {
    code: normalized || "UNKNOWN_TERMINAL_FAILURE",
    failure_class: "unclassified_internal_failure",
    customer_document_replacement_required: false,
    retry_safe: false,
  };
}
